/**
 * Нормализация названия предмета из расписания:
 * 1. Пробелы вокруг точек: «Адаптив . физ-ра» → «Адаптив. физ-ра»
 *    (убрать пробел перед точкой, ровно один пробел после).
 * 2. Известная опечатка: «Разговоры о важн ом» → «Разговоры о важном».
 * 3. Trim + схлопывание повторных пробелов.
 */
export function normalizeSubject(name: string): string {
  return name
    .replace(/важн\s+ом/g, 'важном') // опечатка «важн ом»
    .replace(/\s*\.\s*/g, '. ') // пробелы вокруг точек
    .replace(/\s+/g, ' ') // повторные пробелы
    .replace(/\.\s*$/, '.') // точка в конце — без пробела после
    .trim()
}
